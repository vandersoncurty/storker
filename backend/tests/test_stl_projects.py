def test_update_project_title(client):
    fake_stl = BytesIO(b"solid test\nendsolid test\n")
    resp = client.post("/stl/upload", files={"files": ("model.stl", fake_stl, "application/sla")})
    proj_id = resp.json()["id"]
    stl_id = resp.json()["files"][0]["id"]

    gcode_content = b"; GCode fake\nG28\n"
    client.post(f"/stl/projects/{proj_id}/link-gcode?stl_file_id={stl_id}",
                files={"file": ("model.gcode", gcode_content, "text/plain")})

    resp2 = client.patch(f"/stl/projects/{proj_id}", json={"title": "Meu Modelo", "description": "Descrição"})
    assert resp2.status_code == 200
    assert resp2.json()["title"] == "Meu Modelo"
    assert resp2.json()["info_pending"] is False


