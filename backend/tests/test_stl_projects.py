def test_link_gcode(client):
    fake_stl = BytesIO(b"solid test\nendsolid test\n")
    resp = client.post("/stl/upload", files={"files": ("model.stl", fake_stl, "application/sla")})
    proj_id = resp.json()["id"]
    stl_id = resp.json()["files"][0]["id"]

    gcode_content = (
        b"; generated by PrusaSlicer\n"
        b"; filament used [g] = 12.5\n"
        b"; estimated printing time (normal mode) = 1h 30m 15s\n"
        b"G28\nG1 X0 Y0 Z0.2\n"
    )
    resp2 = client.post(f"/stl/projects/{proj_id}/link-gcode?stl_file_id={stl_id}",
                        files={"file": ("test.gcode", gcode_content, "text/plain")})
    assert resp2.status_code == 200

    client.patch(f"/stl/projects/{proj_id}", json={"title": "Modelo com GCode"})

    prod_resp = client.get("/products/1")
    assert prod_resp.status_code == 200
    assert prod_resp.json()["is_sliced"] is True
    assert prod_resp.json()["filament_grams"] == 12.5


