"""Testes do router de projetos STL — upload, GCode, download, visualização 3D."""

from io import BytesIO


def test_upload_stl(client):
    fake_stl = BytesIO(b"solid test\nfacet normal 0 0 0\nouter loop\nvertex 0 0 0\nvertex 1 0 0\nvertex 0 1 0\nendloop\nendfacet\nendsolid test\n")
    resp = client.post("/stl/upload", files={"files": ("model.stl", fake_stl, "application/sla")})
    assert resp.status_code == 200
    data = resp.json()
    assert data["source"] == "upload"
    assert data["info_pending"] is True
    assert len(data["files"]) == 1


def test_upload_zip_with_stl(client):
    import zipfile
    zip_buf = BytesIO()
    with zipfile.ZipFile(zip_buf, "w") as zf:
        zf.writestr("part.stl", "solid test\nendsolid test\n")
    zip_buf.seek(0)
    resp = client.post("/stl/upload", files={"files": ("model.zip", zip_buf, "application/zip")})
    assert resp.status_code == 200
    data = resp.json()
    assert len(data["files"]) == 1
    assert data["files"][0]["file_type"] == "stl"


